package fr.bebedlastreat.claudeReplay.format;

import com.github.retrooper.packetevents.protocol.packettype.PacketType.Play.Server;

import java.util.UUID;

/**
 * One entry of a replay timeline.
 */
public sealed interface ReplayRecord {

    int tick();

    /**
     * A packet received by one or several recorded players (identical packets received during the same tick by
     * several players are stored once).
     *
     * @param recipients indexes of the recorded players who received it
     * @param payload    packet body, without the packet id
     */
    record Packet(int tick, Server type, int[] recipients, byte[] payload) implements ReplayRecord {

        public boolean isReceivedBy(int player) {
            for (int recipient : recipients) {
                if (recipient == player) {
                    return true;
                }
            }
            return false;
        }
    }

    /**
     * A packet describing a recorded player's own entity (players never receive their own spawn, movements...),
     * generated by the recorder as if another player was watching them.
     */
    record Self(int tick, int subject, Server type, byte[] payload) implements ReplayRecord {
    }

    /**
     * Modifications of the recorded world.
     *
     * @param positions packed with {@link BlockPositions#pack}
     * @param states    global block state ids (protocol of the recording)
     */
    record Blocks(int tick, long[] positions, int[] states) implements ReplayRecord {
    }

    record Event(int tick, ReplayEvent event) implements ReplayRecord {
    }

    sealed interface ReplayEvent {
    }

    /** First appearance of a player in the recording: gives their index. */
    record PlayerRegistered(int index, UUID uuid, String name) implements ReplayEvent {
    }

    /** The player starts to be captured (they are in the recorded world): a full resynchronisation follows. */
    record CaptureStart(int index) implements ReplayEvent {
    }

    /** The player stops being captured (left the world or the recording). */
    record CaptureStop(int index) implements ReplayEvent {
    }

    /** The recording switched world; the index refers to {@code ReplayInfo#worlds()}. */
    record WorldChange(int worldIndex) implements ReplayEvent {
    }

    record Marker(String name, String data) implements ReplayEvent {
    }
}
